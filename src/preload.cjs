const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('claudete', {
  chooseProject: () => ipcRenderer.invoke('project:choose'),
  listClaudeSessions: () => ipcRenderer.invoke('claude:list-sessions'),
  selectClaudeSession: (id) => ipcRenderer.invoke('claude:select-session', id),
  sendClaudeMessage: (payload) => ipcRenderer.invoke('claude:send-message', payload),
  startClaudeLogin: () => ipcRenderer.invoke('claude:login'),
  addAttachment: () => ipcRenderer.invoke('conversation:add-attachment'),
  getState: () => ipcRenderer.invoke('app:state'),
  run: (action) => ipcRenderer.invoke('project:run', action),
  stop: () => ipcRenderer.invoke('project:stop'),
  openSite: () => ipcRenderer.invoke('project:open-site'),
  openClaude: () => ipcRenderer.invoke('claude:open'),
  setPanelMode: (mode) => ipcRenderer.invoke('window:panel', mode),
  setDragging: (dragging) => ipcRenderer.invoke('window:dragging', dragging),
  setMousePassthrough: (ignore) => ipcRenderer.invoke('window:mouse-passthrough', ignore),
  togglePanel: () => ipcRenderer.invoke('mascot:toggle-panel'),
  setMascotRunning: (running) => ipcRenderer.invoke('mascot:running', running),
  setMascotSpeaking: (speaking) => ipcRenderer.invoke('mascot:speaking', speaking),
  deactivate: () => ipcRenderer.invoke('app:deactivate'),
  setSiteUrl: (url) => ipcRenderer.invoke('settings:set-site-url', url),
  toggleWakeWord: () => ipcRenderer.invoke('voice:wake-toggle'),
  sendWakeEvent: (payload) => ipcRenderer.invoke('voice:wake-event', payload),
  onActive: (callback) => ipcRenderer.on('app:active', (_event, value) => callback(value)),
  onNotice: (callback) => ipcRenderer.on('app:notice', (_event, value) => callback(value)),
  onProcess: (callback) => ipcRenderer.on('app:process', (_event, value) => callback(value)),
  onDirection: (callback) => ipcRenderer.on('mascot:direction', (_event, value) => callback(value)),
  onSpeaking: (callback) => ipcRenderer.on('mascot:speaking', (_event, value) => callback(value)),
  onMode: (callback) => ipcRenderer.on('window:mode', (_event, value) => callback(value)),
  onPanelState: (callback) => ipcRenderer.on('mascot:panel-state', (_event, value) => callback(value)),
  onWakeEnabled: (callback) => ipcRenderer.on('app:wake-enabled', (_event, value) => callback(value)),
  onWakeEvent: (callback) => ipcRenderer.on('voice:wake-event', (_event, value) => callback(value)),
});
